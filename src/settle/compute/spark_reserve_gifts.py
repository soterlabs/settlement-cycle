def recognize_spark_reserve_gifts(history):
    index = {b.identity: b for b in history.batches}
    if len(index) != len(history.batches):
        raise ValueError('Duplicate capital transaction')
    grouped = defaultdict(list)
    for event in GIFTS:
        grouped['ethereum:' + event[0]].append(event)
    changed = False
    for identity, gifts in grouped.items():
        b = index.get(identity)
        if b is None:
            continue
        amounts = defaultdict(D)
        for _, block, stamp, token, value in gifts:
            if b.chain != 'ethereum' or b.block != block or b.timestamp != stamp:
                raise ValueError('Spark reserve gift metadata differs')
            amounts[f'ethereum:{HOLDER}:{token}'] += value
        movements = list(b.movements)
        for account, gift in amounts.items():
            found = [m for m in movements if m.account == account]
            if len(found) != 1:
                raise ValueError('Spark reserve gift lacks normalized position')
            m = found[0]
            if m.change < gift - D('1e-8'):
                raise ValueError('Spark reserve gift exceeds observed position receipt')
            if abs(m.external_income - gift) <= D('1e-8'):
                continue  # Current extraction already recognizes this exact gift.
            if m.external_income:
                raise ValueError('Spark reserve gift has conflicting income attribution')
            # A transaction can contain another receipt in this same token.
            # Recognize only the directly proven treasury leg, not all ingress.
            movements = [replace(x, external_income=gift) if x.account == account else x for x in movements]
            changed = True
        index[identity] = replace(b, movements=tuple(movements))
    if not changed:
        return history
    return replace(history, batches=tuple(index.values()))
